const COUNTRY_SUFFIXES = [...new Set([...Object.keys(COUNTRIES), ...EXTRA_COUNTRY_NAMES])].sort(
  (left, right) => right.length - left.length || left.localeCompare(right),
)

export function splitCityCountry(line: string): { city: string; country: string } | null {
  const trimmed = line.replace(/,/g, ' ').replace(/\s+/g, ' ').trim()
  if (!trimmed) return null
  for (const country of COUNTRY_SUFFIXES) {
    if (trimmed === country) return null
    const needle = ` ${country}`
    if (!trimmed.endsWith(needle)) continue
    const city = trimmed.slice(0, -needle.length).trim()
    if (!city || /^[0-9]/.test(city)) return null
    return { city, country }
  }
  return null
}
